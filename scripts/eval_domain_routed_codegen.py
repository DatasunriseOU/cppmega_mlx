def build_prompt_graph_for_prompt(
    prompt: DomainEvalPrompt,
    tokenizer: Any,
):
    """Build and bind a production prompt graph to a frozen eval row."""

    if not prompt.prompt_graph_spec:
        raise ValueError(f"prompt {prompt.id!r} has no prompt_graph specification")
    rendered = render_domain_prompt_graph_spec(
        prompt.prompt_graph_spec,
        context=f"prompt {prompt.id!r} prompt_graph",
    )
    if rendered != prompt.prompt:
        raise ValueError(
            f"prompt {prompt.id!r}: prompt_graph rendered text does not match prompt"
        )
    graph = build_domain_prompt_graph(
        tokenizer,
        prompt.prompt_graph_spec,
        context=f"prompt {prompt.id!r} prompt_graph",
    )
    if not prompt.prompt_token_ids or not prompt.prompt_sidecars:
        raise ValueError(
            f"prompt {prompt.id!r}: production prompt graph requires frozen token sidecars"
        )
    if tuple(graph.token_ids) != tuple(prompt.prompt_token_ids):
        raise ValueError(
            f"prompt {prompt.id!r}: constructed token ids differ from frozen prompt"
        )
    for column in EVAL_TOKEN_SIDECARS + EVAL_EDGE_SIDECARS:
        expected = tuple(prompt.prompt_sidecars.get(column, ()))
        actual = tuple(graph.eval_sidecars[column])
        if actual != expected:
            raise ValueError(
                f"prompt {prompt.id!r}: constructed {column} differs from frozen prompt"
            )
    return graph


def _static_prompt_sidecar_check(prompt: DomainEvalPrompt) -> dict[str, Any]:
    if not prompt.prompt_token_ids or not prompt.prompt_sidecars:
        return _failure(
            "static_prompt_sidecars_failed",
            "sidecar_structure oracle requires frozen prompt_token_ids and prompt_sidecars",
        )
    try:
        validate_prompt_sidecars(
            prompt.prompt_token_ids,
            prompt.prompt_sidecars,
            prompt.required_domains,
            prompt.expected_sidecars,
            context=f"prompt {prompt.id!r}",
        )
        _validate_expected_sidecars(
            prompt.required_domains,
            prompt.expected_sidecars,
            context=f"prompt {prompt.id!r}",
        )
        frozen_graph = domain_prompt_graph_from_frozen(
            prompt.prompt_token_ids,
            {
                column: prompt.prompt_sidecars.get(column, ())
                for column in (*EVAL_TOKEN_SIDECARS, *EVAL_EDGE_SIDECARS)
            },
            part_ranges=prompt.prompt_graph_spec.get("part_ranges")
            if prompt.prompt_graph_spec
            else None,
            context=f"prompt {prompt.id!r}",
        )
    except ValueError as exc:
        return _failure("static_prompt_sidecars_failed", str(exc))

    domain_ids = [int(value) for value in prompt.prompt_sidecars["token_domain_ids"]]
    required_domain_ids = set(
        _prompt_domain_id(name, context=f"prompt {prompt.id!r}")
        for name in prompt.required_domains
    )
    diagnostic_edges = prompt.prompt_sidecars.get("token_diagnostic_edges", ())
    cross_edges = prompt.prompt_sidecars.get("token_cross_domain_edges", ())
    if any(
        DomainKind(int(domain_id)) in _DIAGNOSTIC_DOMAINS
        for domain_id in required_domain_ids
    ) and not diagnostic_edges:
        return _failure(
            "static_prompt_sidecars_failed",
            "diagnostic required domain has no token_diagnostic_edges",
        )
    if len(required_domain_ids) > 1:
        if not cross_edges:
            return _failure(
                "static_prompt_sidecars_failed",
                "multiple required domains need token_cross_domain_edges",
            )
        if not any(
            domain_ids[int(edge["from"])] != domain_ids[int(edge["to"])]
            for edge in cross_edges
        ):
            return _failure(
                "static_prompt_sidecars_failed",
                "token_cross_domain_edges must connect distinct domain ids",
            )
    receipt = prompt.static_prompt_sidecar_receipt()
    return {
        "status": "static_prompt_sidecars_passed",
        "required_domains": list(prompt.required_domains),
        "cross_domain_edges": len(cross_edges),
        "diagnostic_edges": len(diagnostic_edges),
        "prompt_graph_schema": frozen_graph.schema,
        "prompt_graph_artifact_sha256": frozen_graph.receipt["artifact_sha256"],
        "prompt_graph_part_ranges": [list(item) for item in frozen_graph.part_ranges],
        "static_prompt_sidecar_receipt": receipt,
    }


def sidecar_structure_oracle(
    prompt: DomainEvalPrompt,
    completion: str,
) -> dict[str, Any]:
    if prompt.oracle_kind != ORACLE_SIDECAR_STRUCTURE:
        return _failure(
            "missing_sidecar_oracle",
            f"oracle_kind {prompt.oracle_kind!r} is not sidecar_structure",
        )
    oracle_error = prompt.oracle_contract_error()
    if oracle_error is not None:
        return _failure("missing_sidecar_oracle", oracle_error)
    static_check = _static_prompt_sidecar_check(prompt)
    if static_check["status"] != "static_prompt_sidecars_passed":
        return _failure(
            "sidecar_structure_failed",
            "static prompt sidecar check failed: "
            f"{static_check.get('reason', static_check['status'])}",
            static_prompt_check=static_check,
        )
    try:
        generated = _parse_generated_completion(
            prompt,
            completion,
            context=f"prompt {prompt.id!r} sidecar completion",
            require_relation=len(prompt.required_domains) > 1,
        )
    except (_GeneratedCompletionParseError, _GeneratedCompletionStructureError) as exc:
        return _failure(
            "sidecar_structure_failed",
            str(exc),
            static_prompt_check=static_check,
        )
    return {
        "status": "sidecar_structure_passed",
        "evidence_source": "completion_derived",
        "static_prompt_check": static_check,
        "generated_completion_check": generated,
    }


def run_prompt_oracle(
    prompt: DomainEvalPrompt,
    completion: str,
    *,
    tool_overrides: ToolOverrides | None = None,
) -> dict[str, Any]:
    if prompt.oracle_kind == ORACLE_CPP_COMPILE_RUN:
        return compile_cpp_completion(
            prompt,
            completion,
            tool_overrides=tool_overrides,
        )
    if prompt.oracle_kind == ORACLE_SHELL_SYNTAX:
        return shell_syntax_oracle(
            prompt,
            completion,
            tool_overrides=tool_overrides,
        )
    if prompt.oracle_kind == ORACLE_BUILD_STRUCTURE:
        return build_structure_oracle(prompt, completion)
    if prompt.oracle_kind == ORACLE_DIAGNOSTIC_STRUCTURE:
        return diagnostic_structure_oracle(prompt, completion)
    if prompt.oracle_kind == ORACLE_CROSS_DOMAIN_STRUCTURE:
        return cross_domain_structure_oracle(prompt, completion)
    if prompt.oracle_kind == ORACLE_SIDECAR_STRUCTURE:
        return sidecar_structure_oracle(prompt, completion)
    return _failure(
        "missing_compile_oracle",
        f"unknown oracle_kind {prompt.oracle_kind!r}",
    )


def evaluate(
    prompts: list[DomainEvalPrompt],
    completions: dict[str, str],
    *,
    compile: bool = True,
    tool_overrides: ToolOverrides | None = None,
) -> dict[str, Any]:
    rows: list[dict[str, Any]] = []
    for prompt in prompts:
        completion = completions.get(prompt.id)
        has_completion = completion is not None and bool(completion.strip())
        row: dict[str, Any] = {
            "id": prompt.id,
            "task_type": prompt.task_type,
            "oracle_kind": prompt.oracle_kind,
            "required_domains": list(prompt.required_domains),
            "expected_sidecars": list(prompt.expected_sidecars),
            "static_prompt_sidecar_receipt": prompt.static_prompt_sidecar_receipt(),
            "has_completion": has_completion,
        }
        if not has_completion:
            row["status"] = "missing_completion"
        else:
            assert completion is not None
            row["completion_chars"] = len(completion)
            if compile:
                row.update(
                    run_prompt_oracle(
                        prompt,
                        completion,
                        tool_overrides=tool_overrides,
                    )
                )
            else:
                row["status"] = "not_compiled"
        rows.append(row)
    status_counts = Counter(str(row.get("status")) for row in rows)
    known_statuses = PASS_STATUSES | FAIL_STATUSES
    unknown_statuses = set(status_counts) - known_statuses
    if unknown_statuses:
        raise RuntimeError(
            f"domain eval produced unknown statuses {sorted(unknown_statuses)}"
        )
    failed = sum(status_counts[status] for status in FAIL_STATUSES)
    report = {
        "prompts": len(prompts),
        "completion_rows": len(completions),
        "oracle_passed": sum(status_counts[status] for status in PASS_STATUSES),
        "completion_derived_oracle_passed": sum(
            status_counts[status] for status in PASS_STATUSES
        ),
        "failed": failed,
        "passed": failed == 0,
        "status_counts": dict(sorted(status_counts.items())),
        "rows": rows,
    }
    for status in sorted(known_statuses):
        report[status] = status_counts[status]
    return report


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--prompts", type=Path, default=Path("evals/domain_routed_prompts.jsonl")
    )
    parser.add_argument("--completions", type=Path)
    parser.add_argument("--tokenizer", type=Path, default=DEFAULT_TOKENIZER)
    parser.add_argument(
        "--out", type=Path, default=Path("outputs/evals/domain_routed_codegen.json")
    )
    parser.add_argument("--no-compile", action="store_true")
    args = parser.parse_args()

    prompts = load_prompts(args.prompts)
    static_prompt_graphs_validated = 0
    if any(prompt.prompt_graph_spec for prompt in prompts):
        tokenizer = load_cppmega_tokenizer(args.tokenizer)
        for prompt in prompts:
            if prompt.prompt_graph_spec:
                build_prompt_graph_for_prompt(prompt, tokenizer)
                static_prompt_graphs_validated += 1
    completions = load_completions(args.completions)
    report = evaluate(prompts, completions, compile=not args.no_compile)
    report["static_prompt_graphs_validated"] = static_prompt_graphs_validated
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")
    print(
        json.dumps(
            {
                key: report[key]
                for key in (
                    "prompts",
                    "completion_rows",
                    "oracle_passed",
                    "completion_derived_oracle_passed",
                    "compile_passed",
                    "failed",
                    "passed",
                    "static_prompt_graphs_validated",
                    "status_counts",
                )
            },
            sort_keys=True,
        )
    )
    return 0 if report["passed"] else 2


