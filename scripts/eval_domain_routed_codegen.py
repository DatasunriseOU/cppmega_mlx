def _prompt_domain_id(name: str, *, context: str) -> int:
    canonical = _DOMAIN_NAME_ALIASES.get(name.upper(), name.upper())
    try:
        return int(DomainKind[canonical])
    except KeyError as exc:
        raise ValueError(f"{context}: unknown required domain {name!r}") from exc


def _canonical_prompt_domain(name: Any, *, context: str) -> str:
    raw = str(name).upper()
    canonical = _DOMAIN_NAME_ALIASES.get(raw, raw)
    try:
        return DomainKind[canonical].name
    except KeyError as exc:
        raise ValueError(f"{context}: unknown required domain {name!r}") from exc


def _prompt_domain_kinds(
    required_domains: Sequence[str],
    *,
    context: str,
) -> tuple[DomainKind, ...]:
    return tuple(
        DomainKind(_prompt_domain_id(name, context=context))
        for name in required_domains
    )


def _validate_prompt_domain_markers(
    prompt: str,
    required_domains: Sequence[str],
    *,
    context: str,
) -> None:
    required = set(required_domains)
    stack: list[str] = []
    for match in _DOMAIN_MARKER_RE.finditer(prompt):
        domain = _canonical_prompt_domain(match.group(1), context=context)
        if domain not in required:
            raise ValueError(
                f"{context}: prompt delimiter domain {domain!r} is absent from "
                "required_domains"
            )
        if match.group(2) == "START":
            stack.append(domain)
        elif not stack or stack.pop() != domain:
            raise ValueError(f"{context}: unmatched prompt domain end delimiter {domain}")
    if stack:
        raise ValueError(f"{context}: unclosed prompt domain delimiters {stack}")


def _required_prompt_sidecars(
    required_domains: Sequence[str],
    *,
    context: str,
) -> frozenset[str]:
    domains = set(_prompt_domain_kinds(required_domains, context=context))
    required = {"token_domain_ids", "token_role_ids"}
    if domains.intersection(_SHELL_ORACLE_SPECS):
        required.add("token_shell_edges")
    build_domains = domains.intersection(_BUILD_ORACLE_SPECS)
    if build_domains:
        if build_domains == {DomainKind.CONFIGURE}:
            required.add("token_shell_edges")
        else:
            required.add("token_build_edges")
    if domains.intersection(_DIAGNOSTIC_DOMAINS):
        required.add("token_diagnostic_edges")
    if len(domains) > 1:
        required.add("token_cross_domain_edges")
    return frozenset(required)


def _validate_expected_sidecars(
    required_domains: Sequence[str],
    expected_sidecars: Sequence[str],
    *,
    context: str,
) -> None:
    if len(set(expected_sidecars)) != len(expected_sidecars):
        raise ValueError(f"{context}: expected_sidecars must not contain duplicates")
    missing = sorted(
        _required_prompt_sidecars(required_domains, context=context)
        - set(expected_sidecars)
    )
    if missing:
        raise ValueError(
            f"{context}: required domains need expected sidecars {missing}"
        )


def _prompt_delimiter_domains() -> dict[int, int]:
    result: dict[int, int] = {}
    for domain in DomainKind:
        if domain == DomainKind.UNKNOWN:
            continue
        try:
            start, end = delimiter_token_ids(domain)
        except KeyError:
            continue
        result[int(start)] = int(domain)
        result[int(end)] = int(domain)
    return result


_PROMPT_DELIMITER_DOMAINS = _prompt_delimiter_domains()


def _prompt_start_delimiter_ids() -> frozenset[int]:
    result: set[int] = set()
    for domain in DomainKind:
        if domain == DomainKind.UNKNOWN:
            continue
        try:
            start, _end = delimiter_token_ids(domain)
        except KeyError:
            continue
        result.add(int(start))
    return frozenset(result)


_PROMPT_START_DELIMITER_IDS = _prompt_start_delimiter_ids()


def _normalize_prompt_edge(
    edge: Any,
    *,
    column: str,
    token_count: int,
    context: str,
) -> dict[str, int]:
    if not isinstance(edge, Mapping):
        raise ValueError(f"{context}: {column} entries must be objects")
    src = edge.get("from", edge.get("src"))
    dst = edge.get("to", edge.get("dst"))
    if src is None or dst is None or edge.get("kind") is None:
        raise ValueError(f"{context}: {column} entries require from/to/kind")
    try:
        normalized = {"from": int(src), "to": int(dst), "kind": int(edge["kind"])}
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{context}: {column} edge values must be integers") from exc
    if not (
        0 <= normalized["from"] < token_count
        and 0 <= normalized["to"] < token_count
    ):
        raise ValueError(f"{context}: {column} edge endpoint is outside prompt tokens")
    try:
        actual_family = domain_edge_family(normalized["kind"])
    except ValueError as exc:
        raise ValueError(f"{context}: {column}: {exc}") from exc
    expected_family = _PROMPT_EDGE_FAMILIES[column]
    if actual_family != expected_family:
        raise ValueError(
            f"{context}: {column} edge kind {normalized['kind']} belongs to "
            f"{actual_family}, not {expected_family}"
        )
    return normalized


def validate_prompt_sidecars(
    token_ids: Sequence[Any],
    sidecars: Mapping[str, Sequence[Any]],
    required_domains: Sequence[str],
    expected_sidecars: Sequence[str],
    *,
    context: str = "prompt",
) -> None:
    """Validate a frozen prompt token/sidecar snapshot without model execution."""
    token_values = [int(value) for value in token_ids]
    if not token_values:
        raise ValueError(f"{context}: prompt_token_ids must be non-empty")
    missing = [name for name in expected_sidecars if name not in sidecars]
    if missing:
        raise ValueError(f"{context}: expected sidecars are missing {missing}")
    missing_token = [name for name in _PROMPT_TOKEN_SIDECARS if name not in sidecars]
    if missing_token:
        raise ValueError(
            f"{context}: structured prompt sidecars require all token-aligned "
            f"columns; missing={missing_token}"
        )

    token_count = len(token_values)
    vectors: dict[str, list[int]] = {}
    for column in _PROMPT_TOKEN_SIDECARS:
        try:
            vector = [int(value) for value in sidecars[column]]
        except (TypeError, ValueError) as exc:
            raise ValueError(f"{context}: {column} must be an integer sequence") from exc
        if len(vector) != token_count:
            raise ValueError(
                f"{context}: {column} length {len(vector)} != token_ids length {token_count}"
            )
        vectors[column] = vector

    for value in vectors["token_domain_ids"]:
        try:
            DomainKind(value)
        except ValueError as exc:
            raise ValueError(f"{context}: unknown token_domain_ids value {value}") from exc
    for value in vectors["token_role_ids"]:
        try:
            DomainRoleKind(value)
        except ValueError as exc:
            raise ValueError(f"{context}: unknown token_role_ids value {value}") from exc
    for value in vectors["token_confidence_ids"]:
        try:
            ParseConfidence(value)
        except ValueError as exc:
            raise ValueError(f"{context}: unknown token_confidence_ids value {value}") from exc
    for column in ("token_entity_ids", "token_scope_ids", "token_source_doc_ids"):
        if any(value < 0 for value in vectors[column]):
            raise ValueError(f"{context}: {column} values must be non-negative")
    if any(value <= 0 for value in vectors["token_source_doc_ids"]):
        raise ValueError(f"{context}: token_source_doc_ids values must be positive")
    if any(value <= 0 for value in vectors["token_source_identity_ids"]):
        raise ValueError(f"{context}: token_source_identity_ids values must be positive")

    for column in _PROMPT_EDGE_SIDECARS:
        raw_edges = sidecars.get(column, ())
        if not isinstance(raw_edges, Sequence) or isinstance(raw_edges, (str, bytes)):
            raise ValueError(f"{context}: {column} must be an edge sequence")
        for edge in raw_edges:
            _normalize_prompt_edge(
                edge,
                column=column,
                token_count=token_count,
                context=context,
            )

    represented_domains = set(vectors["token_domain_ids"])
    for name in required_domains:
        domain_id = _prompt_domain_id(str(name), context=context)
        if domain_id not in represented_domains:
            raise ValueError(
                f"{context}: required domain {name!r} is absent from token_domain_ids"
            )

    stack: list[int] = []
    for index, token_id in enumerate(token_values):
        domain_id = vectors["token_domain_ids"][index]
        role_id = vectors["token_role_ids"][index]
        confidence_id = vectors["token_confidence_ids"][index]
        delimiter_domain = _PROMPT_DELIMITER_DOMAINS.get(token_id)
        if delimiter_domain is not None:
            if domain_id != delimiter_domain:
                raise ValueError(
                    f"{context}: delimiter token {token_id} has domain id {domain_id}, "
                    f"expected {delimiter_domain}"
                )
            if role_id != int(DomainRoleKind.DELIMITER):
                raise ValueError(f"{context}: delimiter token {token_id} must have role DELIMITER")
            if confidence_id != int(ParseConfidence.EXACT):
                raise ValueError(f"{context}: delimiter token {token_id} must have EXACT confidence")
            if token_id in _PROMPT_START_DELIMITER_IDS:
                stack.append(delimiter_domain)
            elif not stack or stack.pop() != delimiter_domain:
                raise ValueError(f"{context}: unmatched domain end delimiter {token_id}")
            continue
        if role_id == int(DomainRoleKind.DELIMITER):
            raise ValueError(f"{context}: non-delimiter token {token_id} has DELIMITER role")
        active_domain = stack[-1] if stack else int(DomainKind.UNKNOWN)
        if domain_id != active_domain:
            raise ValueError(
                f"{context}: token {index} domain id {domain_id} does not match "
                f"active domain {active_domain}"
            )
    if stack:
        raise ValueError(f"{context}: unclosed domain delimiters {stack}")


def _prompt_sidecar_receipt(
    token_ids: Sequence[int],
    sidecars: Mapping[str, Sequence[Any]],
) -> dict[str, Any]:
    return {
        "token_count": len(token_ids),
        "columns": sorted(sidecars),
        "edge_counts": {
            column: len(sidecars.get(column, ()))
            for column in _PROMPT_EDGE_SIDECARS
            if column in sidecars
        },
    }


def _oracle_role(value: Any, *, context: str) -> DomainRoleKind:
    try:
        if isinstance(value, str) and not value.isdigit():
            return DomainRoleKind[value.upper()]
        return DomainRoleKind(int(value))
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(f"{context}: unknown required role {value!r}") from exc


def _oracle_edge_kind(value: Any, *, context: str) -> DomainEdgeKind:
    try:
        if isinstance(value, str) and not value.isdigit():
            return DomainEdgeKind[value.upper()]
        return DomainEdgeKind(int(value))
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(f"{context}: unknown required edge kind {value!r}") from exc


def _oracle_sequence(
    spec: Mapping[str, Any],
    key: str,
    *,
    context: str,
) -> tuple[Any, ...]:
    raw = spec.get(key, ())
    if not isinstance(raw, Sequence) or isinstance(raw, (str, bytes)):
        raise ValueError(f"{context}: {key} must be a sequence")
    return tuple(raw)


def _validate_oracle_spec(spec: Mapping[str, Any], *, context: str) -> None:
    required_roles = _oracle_sequence(spec, "required_roles", context=context)
    required_edges = _oracle_sequence(
        spec,
        "required_edge_kinds",
        context=context,
    )
    required_tokens = _oracle_sequence(spec, "required_tokens", context=context)
    forbidden_tokens = _oracle_sequence(spec, "forbidden_tokens", context=context)
    roles = tuple(_oracle_role(value, context=context) for value in required_roles)
    edges = tuple(_oracle_edge_kind(value, context=context) for value in required_edges)
    if len(set(roles)) != len(roles):
        raise ValueError(f"{context}: required_roles must not contain duplicates")
    if len(set(edges)) != len(edges):
        raise ValueError(
            f"{context}: required_edge_kinds must not contain duplicates"
        )
    if any(not isinstance(value, str) or not value for value in required_tokens):
        raise ValueError(f"{context}: required_tokens must contain non-empty strings")
    if any(not isinstance(value, str) or not value for value in forbidden_tokens):
        raise ValueError(f"{context}: forbidden_tokens must contain non-empty strings")
    expected_metadata = spec.get("expected_metadata", {})
    if not isinstance(expected_metadata, Mapping):
        raise ValueError(f"{context}: expected_metadata must be an object")


def _normalized_oracle_spec(
    spec: Mapping[str, Any],
    *,
    context: str,
) -> dict[str, Any]:
    _validate_oracle_spec(spec, context=context)
    return {
        "required_roles": tuple(
            _oracle_role(value, context=context)
            for value in _oracle_sequence(spec, "required_roles", context=context)
        ),
        "required_edge_kinds": tuple(
            _oracle_edge_kind(value, context=context)
            for value in _oracle_sequence(
                spec,
                "required_edge_kinds",
                context=context,
            )
        ),
        "required_tokens": tuple(
            str(value)
            for value in _oracle_sequence(spec, "required_tokens", context=context)
        ),
        "forbidden_tokens": tuple(
            str(value)
            for value in _oracle_sequence(spec, "forbidden_tokens", context=context)
        ),
        "expected_metadata": dict(spec.get("expected_metadata", {})),
    }


def _nonnegative_int(value: Any, *, field: str, context: str) -> int:
    if isinstance(value, bool):
        raise ValueError(f"{context}: {field} must be a non-negative integer")
    try:
        normalized = int(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"{context}: {field} must be a non-negative integer"
        ) from exc
    if normalized < 0:
        raise ValueError(f"{context}: {field} must be non-negative")
    return normalized


def _normalized_generated_relation(
    raw: Mapping[str, Any],
    *,
    required_domains: Sequence[str],
    context: str,
    infer_blocks: bool = False,
) -> dict[str, Any]:
    if not isinstance(raw, Mapping):
        raise ValueError(f"{context}: generated relation must be an object")
    required = {
        "from_domain",
        "to_domain",
        "from_role",
        "to_role",
        "kind",
    }
    missing = sorted(field for field in required if field not in raw)
    if missing:
        raise ValueError(f"{context}: generated relation is missing {missing}")
    from_domain = _canonical_prompt_domain(
        raw["from_domain"],
        context=context,
    )
    to_domain = _canonical_prompt_domain(
        raw["to_domain"],
        context=context,
    )
    if from_domain == to_domain:
        raise ValueError(f"{context}: generated relation domains must differ")
    declared_domains = set(required_domains)
    if from_domain not in declared_domains or to_domain not in declared_domains:
        raise ValueError(
            f"{context}: generated relation domains must be declared in required_domains"
        )
    from_role = _oracle_role(raw["from_role"], context=context)
    to_role = _oracle_role(raw["to_role"], context=context)
    edge_kind = _oracle_edge_kind(raw["kind"], context=context)
    if domain_edge_family(edge_kind) != "cross_domain":
        raise ValueError(
            f"{context}: generated relation kind {edge_kind.name} must belong to cross_domain"
        )
    from_block = raw.get("from_block")
    to_block = raw.get("to_block")
    if infer_blocks and (from_block is None or to_block is None):
        try:
            from_block = tuple(required_domains).index(from_domain)
            to_block = tuple(required_domains).index(to_domain)
        except ValueError as exc:
            raise ValueError(
                f"{context}: generated relation domains have no declared block"
            ) from exc
    if from_block is None or to_block is None:
        raise ValueError(
            f"{context}: generated relation requires from_block and to_block"
        )
    normalized_from_block = _nonnegative_int(
        from_block,
        field="from_block",
        context=context,
    )
    normalized_to_block = _nonnegative_int(
        to_block,
        field="to_block",
        context=context,
    )
    if normalized_from_block == normalized_to_block:
        raise ValueError(f"{context}: generated relation blocks must differ")
    return {
        "from_block": normalized_from_block,
        "to_block": normalized_to_block,
        "from_domain": from_domain,
        "to_domain": to_domain,
        "from_role": from_role.name,
        "to_role": to_role.name,
        "from_occurrence": _nonnegative_int(
            raw.get("from_occurrence", 0),
            field="from_occurrence",
            context=context,
        ),
        "to_occurrence": _nonnegative_int(
            raw.get("to_occurrence", 0),
            field="to_occurrence",
            context=context,
        ),
        "kind": edge_kind.name,
    }


def _normalized_generated_contract(
    spec: Mapping[str, Any],
    required_domains: Sequence[str],
    *,
    context: str,
    require_relation: bool,
) -> dict[str, Any]:
    raw_parts = spec.get("parts")
    if not isinstance(raw_parts, Sequence) or isinstance(raw_parts, (str, bytes)):
        raise ValueError(f"{context}: generated output parts must be a sequence")
    if len(raw_parts) != len(required_domains):
        raise ValueError(
            f"{context}: generated output parts length {len(raw_parts)} != "
            f"required_domains length {len(required_domains)}"
        )
    parts: list[dict[str, Any]] = []
    for index, raw_part in enumerate(raw_parts):
        if not isinstance(raw_part, Mapping):
            raise ValueError(f"{context}: generated output part {index} must be an object")
        domain = _canonical_prompt_domain(
            raw_part.get("domain", required_domains[index]),
            context=f"{context} part {index}",
        )
        expected_domain = _canonical_prompt_domain(
            required_domains[index],
            context=f"{context} part {index}",
        )
        if domain != expected_domain:
            raise ValueError(
                f"{context}: generated output part {index} declares {domain}, "
                f"expected {expected_domain}"
            )
        normalized = _normalized_oracle_spec(
            raw_part,
            context=f"{context} part {index}",
        )
        normalized["domain"] = domain
        parts.append(normalized)

    raw_edge = spec.get("cross_domain_edge")
    if require_relation and not isinstance(raw_edge, Mapping):
        raise ValueError(
            f"{context}: generated output requires cross_domain_edge contract"
        )
    expected_edge = (
        None
        if raw_edge is None
        else _normalized_generated_relation(
            raw_edge,
            required_domains=required_domains,
            context=f"{context} cross_domain_edge",
            infer_blocks=True,
        )
    )
    return {"parts": tuple(parts), "cross_domain_edge": expected_edge}


