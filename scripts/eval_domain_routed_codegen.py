@dataclass(frozen=True)
class DomainEvalPrompt:
    id: str
    task_type: str
    prompt: str
    required_domains: tuple[str, ...]
    expected_sidecars: tuple[str, ...]
    oracle_kind: str = ORACLE_CPP_COMPILE_RUN
    compile_prefix: str = ""
    compile_suffix: str = ""
    run_binary: bool = False
    prompt_token_ids: tuple[int, ...] = ()
    prompt_sidecars: Mapping[str, tuple[Any, ...]] = field(default_factory=dict)
    oracle_spec: Mapping[str, Any] = field(default_factory=dict)
    prompt_graph_spec: Mapping[str, Any] = field(default_factory=dict)

    def oracle_contract_error(self) -> str | None:
        if self.oracle_kind not in ORACLE_KINDS:
            return f"unknown oracle_kind {self.oracle_kind!r}"
        try:
            domains = set(
                _prompt_domain_kinds(
                    self.required_domains,
                    context=f"prompt {self.id!r}",
                )
            )
        except ValueError as exc:
            return str(exc)
        if self.oracle_kind == ORACLE_CPP_COMPILE_RUN:
            if DomainKind.CPP not in domains:
                return "cpp_compile_run oracle requires required_domains to include CPP"
            if not (self.compile_prefix.strip() or self.compile_suffix.strip()):
                return "compile_prefix or compile_suffix must provide a test wrapper"
            if not self.run_binary:
                return "run_binary must be true so compiled output is executed"
            return None
        if self.compile_prefix.strip() or self.compile_suffix.strip() or self.run_binary:
            return (
                f"{self.oracle_kind} oracle cannot declare compile_prefix, "
                "compile_suffix, or run_binary"
            )
        if self.oracle_kind == ORACLE_SHELL_SYNTAX:
            shell_domains = domains.intersection(_SHELL_ORACLE_SPECS)
            if len(shell_domains) != 1:
                return (
                    "shell_syntax oracle requires exactly one shell domain "
                    "(BASH, ZSH, KSH, or SH)"
                )
            try:
                _normalized_oracle_spec(
                    self.oracle_spec,
                    context=f"prompt {self.id!r} shell oracle",
                )
            except ValueError as exc:
                return str(exc)
            return None
        if self.oracle_kind == ORACLE_BUILD_STRUCTURE:
            build_domains = domains.intersection(_BUILD_ORACLE_SPECS)
            if len(build_domains) != 1:
                return (
                    "build_structure oracle requires exactly one build/config "
                    "domain (CMAKE, MAKE, NINJA, BAZEL, or CONFIGURE)"
                )
            try:
                _normalized_oracle_spec(
                    self.oracle_spec,
                    context=f"prompt {self.id!r} build oracle",
                )
            except ValueError as exc:
                return str(exc)
            return None
        if self.oracle_kind == ORACLE_DIAGNOSTIC_STRUCTURE:
            diagnostic_domains = domains.intersection(_DIAGNOSTIC_ORACLE_SPECS)
            if len(diagnostic_domains) != 1:
                return (
                    "diagnostic_structure oracle requires exactly one declared "
                    "diagnostic domain"
                )
            try:
                _normalized_oracle_spec(
                    self.oracle_spec,
                    context=f"prompt {self.id!r} diagnostic oracle",
                )
            except ValueError as exc:
                return str(exc)
            return None
        if self.oracle_kind == ORACLE_CROSS_DOMAIN_STRUCTURE:
            if len(domains) < 2:
                return "cross_domain_structure oracle requires at least two domains"
            try:
                _normalized_generated_contract(
                    self.oracle_spec,
                    self.required_domains,
                    context=f"prompt {self.id!r} cross-domain oracle",
                    require_relation=True,
                )
            except ValueError as exc:
                return str(exc)
            return None
        if not self.prompt_token_ids or not self.prompt_sidecars:
            return "sidecar_structure oracle requires frozen prompt_token_ids and prompt_sidecars"
        if not (
            domains.intersection(_DIAGNOSTIC_DOMAINS)
            or "token_cross_domain_edges" in self.expected_sidecars
        ):
            return (
                "sidecar_structure oracle requires a diagnostic domain or "
                "cross-domain sidecar"
            )
        try:
            _normalized_generated_contract(
                self.oracle_spec,
                self.required_domains,
                context=f"prompt {self.id!r} sidecar oracle",
                require_relation=len(domains) > 1,
            )
        except ValueError as exc:
            return str(exc)
        return None

    def executable_oracle_error(self) -> str | None:
        """Compatibility name for callers that specifically request C++ execution."""

        if self.oracle_kind != ORACLE_CPP_COMPILE_RUN:
            return f"oracle_kind {self.oracle_kind!r} is not cpp_compile_run"
        return self.oracle_contract_error()

    def sidecar_receipt(self) -> dict[str, Any]:
        return _prompt_sidecar_receipt(self.prompt_token_ids, self.prompt_sidecars)

    def static_prompt_sidecar_receipt(self) -> dict[str, Any]:
        return self.sidecar_receipt()

    @classmethod
    def from_row(
        cls, row: dict[str, Any], *, path: Path, line_no: int
    ) -> "DomainEvalPrompt":
        missing = [
            key
            for key in (
                "id",
                "task_type",
                "prompt",
                "required_domains",
                "oracle_kind",
            )
            if key not in row
        ]
        if missing:
            raise ValueError(
                f"{path}:{line_no}: missing required prompt fields {missing}"
            )
        raw_required_domains = row["required_domains"]
        if not isinstance(raw_required_domains, Sequence) or isinstance(
            raw_required_domains, (str, bytes)
        ):
            raise ValueError(f"{path}:{line_no}: required_domains must be a sequence")
        required_domains = tuple(
            _canonical_prompt_domain(x, context=f"{path}:{line_no}")
            for x in raw_required_domains
        )
        if not required_domains:
            raise ValueError(f"{path}:{line_no}: required_domains must be non-empty")
        if len(set(required_domains)) != len(required_domains):
            raise ValueError(f"{path}:{line_no}: required_domains must not contain duplicates")
        raw_expected_sidecars = row.get("expected_sidecars", ())
        if not isinstance(raw_expected_sidecars, Sequence) or isinstance(
            raw_expected_sidecars, (str, bytes)
        ):
            raise ValueError(f"{path}:{line_no}: expected_sidecars must be a sequence")
        expected_sidecars = tuple(str(x) for x in raw_expected_sidecars)
        _validate_expected_sidecars(
            required_domains,
            expected_sidecars,
            context=f"{path}:{line_no}",
        )
        oracle_kind = row["oracle_kind"]
        if not isinstance(oracle_kind, str):
            raise ValueError(f"{path}:{line_no}: oracle_kind must be a string")
        if oracle_kind not in ORACLE_KINDS:
            raise ValueError(
                f"{path}:{line_no}: unknown oracle_kind {oracle_kind!r}; "
                f"expected one of {sorted(ORACLE_KINDS)}"
            )
        _validate_prompt_domain_markers(
            str(row["prompt"]),
            required_domains,
            context=f"{path}:{line_no}",
        )
        raw_token_ids = row.get("prompt_token_ids")
        raw_sidecars = row.get("prompt_sidecars")
        if (raw_token_ids is None) != (raw_sidecars is None):
            raise ValueError(
                f"{path}:{line_no}: prompt_token_ids and prompt_sidecars must be "
                "provided together"
            )
        prompt_token_ids: tuple[int, ...] = ()
        prompt_sidecars: dict[str, tuple[Any, ...]] = {}
        raw_oracle_spec = row.get("oracle_spec", row.get("oracle", {}))
        if not isinstance(raw_oracle_spec, Mapping):
            raise ValueError(f"{path}:{line_no}: oracle_spec must be an object")
        oracle_spec = dict(raw_oracle_spec)
        raw_prompt_graph_spec = row.get("prompt_graph", {})
        if not isinstance(raw_prompt_graph_spec, Mapping):
            raise ValueError(f"{path}:{line_no}: prompt_graph must be an object")
        prompt_graph_spec = dict(raw_prompt_graph_spec)
        if prompt_graph_spec:
            try:
                render_domain_prompt_graph_spec(
                    prompt_graph_spec,
                    context=f"{path}:{line_no} prompt_graph",
                )
            except ValueError as exc:
                raise ValueError(str(exc)) from exc
        if raw_token_ids is not None:
            if not isinstance(raw_token_ids, Sequence) or isinstance(
                raw_token_ids, (str, bytes)
            ):
                raise ValueError(
                    f"{path}:{line_no}: prompt_token_ids must be an integer sequence"
                )
            if not isinstance(raw_sidecars, Mapping):
                raise ValueError(f"{path}:{line_no}: prompt_sidecars must be an object")
            prompt_token_ids = tuple(int(value) for value in raw_token_ids)
            for column, values in raw_sidecars.items():
                if not isinstance(values, Sequence) or isinstance(values, (str, bytes)):
                    raise ValueError(
                        f"{path}:{line_no}: prompt sidecar {column!r} must be a sequence"
                    )
                column_name = str(column)
                if column_name in _PROMPT_EDGE_SIDECARS:
                    prompt_sidecars[column_name] = tuple(
                        _normalize_prompt_edge(
                            edge,
                            column=column_name,
                            token_count=len(prompt_token_ids),
                            context=f"{path}:{line_no}",
                        )
                        for edge in values
                    )
                else:
                    prompt_sidecars[column_name] = tuple(values)
            validate_prompt_sidecars(
                prompt_token_ids,
                prompt_sidecars,
                required_domains,
                expected_sidecars,
                context=f"{path}:{line_no}",
            )
        prompt = cls(
            id=str(row["id"]),
            task_type=str(row["task_type"]),
            prompt=str(row["prompt"]),
            required_domains=required_domains,
            expected_sidecars=expected_sidecars,
            oracle_kind=oracle_kind,
            compile_prefix=str(row.get("compile_prefix", "")),
            compile_suffix=str(row.get("compile_suffix", "")),
            run_binary=bool(row.get("run_binary", False)),
            prompt_token_ids=prompt_token_ids,
            prompt_sidecars=prompt_sidecars,
            oracle_spec=oracle_spec,
            prompt_graph_spec=prompt_graph_spec,
        )
        oracle_error = prompt.oracle_contract_error()
        if oracle_error is not None:
            raise ValueError(
                f"{path}:{line_no}: prompt {prompt.id!r} has invalid "
                f"{prompt.oracle_kind} oracle contract: {oracle_error}"
            )
        return prompt


def load_prompts(path: Path) -> list[DomainEvalPrompt]:
    prompts: list[DomainEvalPrompt] = []
    seen: set[str] = set()
    with path.open("r", encoding="utf-8") as fh:
        for line_no, line in enumerate(fh, 1):
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            prompt = DomainEvalPrompt.from_row(row, path=path, line_no=line_no)
            if prompt.id in seen:
                raise ValueError(f"{path}:{line_no}: duplicate prompt id {prompt.id!r}")
            seen.add(prompt.id)
            prompts.append(prompt)
    if not prompts:
        raise ValueError(f"{path}: no prompts")
    return prompts


def load_completions(path: Path | None) -> dict[str, str]:
    if path is None:
        return {}
    completions: dict[str, str] = {}
    with path.open("r", encoding="utf-8") as fh:
        for line_no, line in enumerate(fh, 1):
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            if "id" not in row or "completion" not in row:
                raise ValueError(
                    f"{path}:{line_no}: completion rows need id and completion"
                )
            completion_id = str(row["id"])
            if completion_id in completions:
                raise ValueError(
                    f"{path}:{line_no}: duplicate completion id {completion_id!r}"
                )
            completions[completion_id] = str(row["completion"])
    return completions


ToolOverrides = Mapping[str, str | None]


def _resolve_tool(
    logical_name: str,
    candidates: Sequence[str],
    tool_overrides: ToolOverrides | None,
) -> str | None:
    if tool_overrides is not None and logical_name in tool_overrides:
        return tool_overrides[logical_name]
    for name in candidates:
        path = shutil.which(name)
        if path:
            return path
    return None


def _find_cpp_compiler(tool_overrides: ToolOverrides | None = None) -> str | None:
    return _resolve_tool("cpp", ("clang++", "c++", "g++"), tool_overrides)


def _parsed_receipt(parsed: Any) -> dict[str, Any]:
    return {
        "parser_adapter": parsed.metadata.get("parser_adapter"),
        "token_count": len(parsed.tokens),
        "edge_count": len(parsed.edges),
        "metadata": {
            key: value
            for key, value in parsed.metadata.items()
            if not key.startswith("_")
        },
        "confidence_ids": sorted(set(int(value) for value in parsed.confidence_ids)),
    }


def _single_domain(
    prompt: DomainEvalPrompt,
    allowed: Mapping[DomainKind, Any],
) -> DomainKind | None:
    domains = set(_prompt_domain_kinds(prompt.required_domains, context=prompt.id))
    selected = domains.intersection(allowed)
    return next(iter(selected)) if len(selected) == 1 else None


def _parsed_oracle_error(
    parsed: Any,
    oracle_spec: Mapping[str, Any],
    *,
    allowed_domains: frozenset[DomainKind],
    context: str,
) -> str | None:
    if parsed.domain not in allowed_domains:
        return (
            f"{context}: parser returned domain {parsed.domain.name}, "
            f"expected one of {sorted(domain.name for domain in allowed_domains)}"
        )
    if parsed.metadata.get("unsupported_syntax") or set(parsed.confidence_ids) == {
        int(ParseConfidence.RAW)
    }:
        return str(
            parsed.metadata.get(
                "unsupported_syntax",
                "parser marked output RAW",
            )
        )
    normalized = _normalized_oracle_spec(oracle_spec, context=context)
    token_texts = {str(token.text) for token in parsed.tokens}
    missing_tokens = [
        token for token in normalized["required_tokens"] if token not in token_texts
    ]
    if missing_tokens:
        return f"{context}: required tokens are absent {missing_tokens}"
    forbidden = [
        token for token in normalized["forbidden_tokens"] if token in token_texts
    ]
    if forbidden:
        return f"{context}: forbidden tokens are present {forbidden}"
    role_ids = {int(value) for value in parsed.role_ids}
    missing_roles = [
        role.name
        for role in normalized["required_roles"]
        if int(role) not in role_ids
    ]
    if missing_roles:
        return f"{context}: required roles are absent {missing_roles}"
    edge_kinds = {int(edge[2]) for edge in parsed.edges}
    missing_edges = [
        edge.name
        for edge in normalized["required_edge_kinds"]
        if int(edge) not in edge_kinds
    ]
    if missing_edges:
        return f"{context}: required edge kinds are absent {missing_edges}"
    metadata_mismatches = {
        str(key): {
            "expected": expected,
            "actual": parsed.metadata.get(key),
        }
        for key, expected in normalized["expected_metadata"].items()
        if parsed.metadata.get(key) != expected
    }
    if metadata_mismatches:
        return f"{context}: metadata contract mismatch {metadata_mismatches}"
    return None


def _typed_output_receipt(parsed: Any) -> dict[str, Any]:
    receipt = _parsed_receipt(parsed)
    receipt["domain"] = parsed.domain.name
    receipt["roles"] = sorted(
        {
            DomainRoleKind(int(value)).name
            for value in parsed.role_ids
            if int(value) != int(DomainRoleKind.NONE)
        }
    )
    receipt["edge_kinds"] = sorted(
        {DomainEdgeKind(int(edge[2])).name for edge in parsed.edges}
    )
    return receipt


def _output_domain_blocks(
    text: str,
    *,
    context: str,
) -> list[tuple[str, str]]:
    """Extract sequential typed output blocks and reject malformed nesting."""

    matches = list(_OUTPUT_DOMAIN_MARKER_RE.finditer(text))
    if not matches:
        raise ValueError(f"{context}: completion contains no typed domain blocks")
    blocks: list[tuple[str, str]] = []
    open_domain: str | None = None
    body_start = 0
    cursor = 0
    for match in matches:
        if open_domain is None and text[cursor : match.start()].strip():
            raise ValueError(
                f"{context}: completion contains untyped text outside domain blocks"
            )
        domain = _canonical_prompt_domain(match.group(1), context=context)
        marker_kind = match.group(2)
        if marker_kind == "START":
            if open_domain is not None:
                raise ValueError(
                    f"{context}: nested output domain {domain!r} inside {open_domain!r}"
                )
            open_domain = domain
            body_start = match.end()
            cursor = match.end()
            continue
        if open_domain != domain:
            raise ValueError(
                f"{context}: output domain end {domain!r} does not match {open_domain!r}"
            )
        blocks.append((domain, text[body_start : match.start()]))
        open_domain = None
        cursor = match.end()
    if open_domain is not None:
        raise ValueError(f"{context}: unclosed output domain {open_domain!r}")
    if text[cursor:].strip():
        raise ValueError(
            f"{context}: completion contains untyped text outside domain blocks"
        )
    if not blocks:
        raise ValueError(f"{context}: completion contains no typed domain blocks")
    return blocks


def _extract_generated_relations(
    text: str,
    *,
    required_domains: Sequence[str],
    context: str,
) -> tuple[str, list[dict[str, Any]]]:
    relations: list[dict[str, Any]] = []
    for match in _GENERATED_CROSS_DOMAIN_EDGE_RE.finditer(text):
        try:
            payload = json.loads(match.group("payload"))
        except json.JSONDecodeError as exc:
            raise _GeneratedCompletionParseError(
                f"{context}: generated cross-domain relation is not valid JSON: {exc}"
            ) from exc
        try:
            relations.append(
                _normalized_generated_relation(
                    payload,
                    required_domains=required_domains,
                    context=f"{context} generated relation {len(relations)}",
                )
            )
        except ValueError as exc:
            raise _GeneratedCompletionStructureError(str(exc)) from exc
    stripped = _GENERATED_CROSS_DOMAIN_EDGE_RE.sub("\n", text)
    if _GENERATED_CROSS_DOMAIN_EDGE_MARKER_RE.search(stripped):
        raise _GeneratedCompletionParseError(
            f"{context}: malformed generated cross-domain relation marker"
        )
    return stripped, relations


def _output_parser_for_domain(
    domain: DomainKind,
) -> tuple[Any, frozenset[DomainKind]] | None:
    if domain in _SHELL_ORACLE_SPECS:
        return _SHELL_ORACLE_SPECS[domain][1], frozenset({domain})
    if domain in _BUILD_ORACLE_SPECS:
        return _BUILD_ORACLE_SPECS[domain], frozenset({domain})
    return _DIAGNOSTIC_ORACLE_SPECS.get(domain)


def _parse_generated_completion(
    prompt: DomainEvalPrompt,
    completion: str,
    *,
    context: str,
    require_relation: bool,
) -> dict[str, Any]:
    """Validate typed blocks and relations emitted by the completion itself."""

    try:
        contract = _normalized_generated_contract(
            prompt.oracle_spec,
            prompt.required_domains,
            context=f"prompt {prompt.id!r} generated completion",
            require_relation=require_relation,
        )
    except ValueError as exc:
        raise _GeneratedCompletionStructureError(str(exc)) from exc

    stripped, relations = _extract_generated_relations(
        completion,
        required_domains=prompt.required_domains,
        context=context,
    )
    try:
        blocks = _output_domain_blocks(stripped, context=context)
    except ValueError as exc:
        raise _GeneratedCompletionParseError(str(exc)) from exc
    expected_domains = [part["domain"] for part in contract["parts"]]
    actual_domains = [domain for domain, _body in blocks]
    missing_domains = [
        domain for domain in expected_domains if domain not in actual_domains
    ]
    if missing_domains:
        raise _GeneratedCompletionStructureError(
            f"{context}: completion is missing required typed domains "
            f"{missing_domains}"
        )
    if len(blocks) != len(contract["parts"]):
        raise _GeneratedCompletionStructureError(
            f"{context}: completion emitted {len(blocks)} typed domain blocks, "
            f"expected {len(contract['parts'])}"
        )

    parsed_blocks: list[tuple[str, Any]] = []
    block_receipts: list[dict[str, Any]] = []
    for index, (domain_name, body) in enumerate(blocks):
        part_spec = contract["parts"][index]
        expected_domain = part_spec["domain"]
        if domain_name != expected_domain:
            raise _GeneratedCompletionStructureError(
                f"{context}: block {index} declares {domain_name}, "
                f"expected {expected_domain}"
            )
        domain = _prompt_domain_kinds(
            (domain_name,),
            context=f"{context} block {index}",
        )[0]
        parser_spec = _output_parser_for_domain(domain)
        if parser_spec is None:
            raise _GeneratedCompletionStructureError(
                f"{context}: no typed output parser for domain {domain.name}"
            )
        parser, allowed_domains = parser_spec
        try:
            parsed = parser(body)
            parsed.validate()
        except (IndexError, TypeError, ValueError) as exc:
            raise _GeneratedCompletionParseError(
                f"{context} block {index} {domain.name.lower()} parser failed: {exc}"
            ) from exc
        try:
            contract_error = _parsed_oracle_error(
                parsed,
                part_spec,
                allowed_domains=allowed_domains,
                context=f"{context} block {index}",
            )
        except ValueError as exc:
            raise _GeneratedCompletionStructureError(str(exc)) from exc
        if contract_error is not None:
            raise _GeneratedCompletionStructureError(contract_error)
        if domain in _SHELL_ORACLE_SPECS:
            shell_prompt = DomainEvalPrompt(
                id=f"{prompt.id}:generated-block:{index}",
                task_type="generated_domain_block",
                prompt=body,
                required_domains=(domain.name,),
                expected_sidecars=(),
                oracle_kind=ORACLE_SHELL_SYNTAX,
                oracle_spec=part_spec,
            )
            shell_result = shell_syntax_oracle(shell_prompt, body)
            if shell_result["status"] != "shell_syntax_passed":
                raise _GeneratedCompletionStructureError(
                    f"{context} block {index} failed its executable syntax oracle: "
                    f"{shell_result.get('reason', shell_result['status'])}"
                )
        parsed_blocks.append((domain_name, parsed))
        block_receipts.append(_typed_output_receipt(parsed))

    generated_edge: dict[str, Any] | None = None
    expected_edge = contract["cross_domain_edge"]
    if require_relation:
        if not relations:
            raise _GeneratedCompletionStructureError(
                f"{context}: completion emitted no generated cross-domain relation"
            )
        if len(relations) != 1:
            raise _GeneratedCompletionStructureError(
                f"{context}: completion emitted {len(relations)} generated "
                "cross-domain relations; expected exactly one"
            )
        actual_edge = relations[0]
        if expected_edge is None:
            raise _GeneratedCompletionStructureError(
                f"{context}: prompt has no expected cross-domain relation contract"
            )
        mismatches = {
            key: {"expected": expected_edge[key], "actual": actual_edge[key]}
            for key in expected_edge
            if expected_edge[key] != actual_edge[key]
        }
        if mismatches:
            raise _GeneratedCompletionStructureError(
                f"{context}: generated cross-domain relation does not match the "
                f"prompt contract: {mismatches}"
            )
        from_block = actual_edge["from_block"]
        to_block = actual_edge["to_block"]
        if from_block >= len(parsed_blocks) or to_block >= len(parsed_blocks):
            raise _GeneratedCompletionStructureError(
                f"{context}: generated relation block endpoint is outside completion blocks"
            )
        if parsed_blocks[from_block][0] != actual_edge["from_domain"]:
            raise _GeneratedCompletionStructureError(
                f"{context}: generated relation from_domain does not match its block"
            )
        if parsed_blocks[to_block][0] != actual_edge["to_domain"]:
            raise _GeneratedCompletionStructureError(
                f"{context}: generated relation to_domain does not match its block"
            )
        from_role = _oracle_role(
            actual_edge["from_role"],
            context=f"{context} generated relation",
        )
        to_role = _oracle_role(
            actual_edge["to_role"],
            context=f"{context} generated relation",
        )

        def resolve_role(block_index: int, role: DomainRoleKind, occurrence: int) -> int:
            candidates = [
                token_index
                for token_index, role_id in enumerate(
                    parsed_blocks[block_index][1].role_ids
                )
                if int(role_id) == int(role)
            ]
            if occurrence >= len(candidates):
                raise _GeneratedCompletionStructureError(
                    f"{context}: generated relation {role.name} occurrence "
                    f"{occurrence} is absent from block {block_index}"
                )
            return candidates[occurrence]

        generated_edge = dict(actual_edge)
        generated_edge["from_token"] = resolve_role(
            from_block,
            from_role,
            actual_edge["from_occurrence"],
        )
        generated_edge["to_token"] = resolve_role(
            to_block,
            to_role,
            actual_edge["to_occurrence"],
        )
    elif relations:
        raise _GeneratedCompletionStructureError(
            f"{context}: completion emitted a cross-domain relation without a "
            "relation contract"
        )

    result: dict[str, Any] = {
        "status": "generated_completion_structure_passed",
        "evidence_source": "completion",
        "relation_contract": "generated_cross_domain_edge_marker_v1",
        "block_count": len(parsed_blocks),
        "blocks": block_receipts,
    }
    if generated_edge is not None:
        result["generated_cross_domain_edge"] = generated_edge
    return result


def _failure(status: str, reason: str, **extra: Any) -> dict[str, Any]:
    return {
        "status": status,
        "reason": reason,
        "failed_closed": True,
        **extra,
    }


def compile_cpp_completion(
    prompt: DomainEvalPrompt,
    completion: str,
    *,
    compiler: str | None = None,
    compile_timeout_s: float = 120.0,
    run_timeout_s: float = 10.0,
    tool_overrides: ToolOverrides | None = None,
) -> dict[str, Any]:
    oracle_error = prompt.executable_oracle_error()
    if oracle_error is not None:
        return _failure("missing_compile_oracle", oracle_error)
    compiler = compiler if compiler is not None else _find_cpp_compiler(tool_overrides)
    if compiler is None:
        return _failure(
            "compile_oracle_unavailable",
            "no local C++ compiler found",
        )
    source = prompt.compile_prefix + completion + prompt.compile_suffix
    with tempfile.TemporaryDirectory(prefix="cppmega-domain-eval-") as tmp:
        src = Path(tmp) / "main.cpp"
        exe = Path(tmp) / "a.out"
        src.write_text(source, encoding="utf-8")
        try:
            proc = subprocess.run(
                [compiler, "-std=c++20", "-Wall", "-Wextra", str(src), "-o", str(exe)],
                capture_output=True,
                text=True,
                timeout=compile_timeout_s,
            )
        except subprocess.TimeoutExpired as exc:
            return _failure(
                "compile_timeout",
                "C++ compiler exceeded the compile timeout",
                timeout_s=compile_timeout_s,
                stderr=str(exc.stderr or "")[-4000:],
            )
        except OSError as exc:
            return _failure("compile_oracle_unavailable", str(exc))
        if proc.returncode != 0:
            return _failure(
                "compile_failed",
                "C++ compilation failed",
                returncode=proc.returncode,
                stderr=proc.stderr[-4000:],
            )
        try:
            run = subprocess.run(
                [str(exe)],
                capture_output=True,
                text=True,
                timeout=run_timeout_s,
            )
        except subprocess.TimeoutExpired as exc:
            return _failure(
                "runtime_timeout",
                "compiled C++ completion exceeded the runtime timeout",
                returncode=proc.returncode,
                timeout_s=run_timeout_s,
                stderr=proc.stderr[-4000:],
                runtime_stdout=str(exc.stdout or "")[-4000:],
                runtime_stderr=str(exc.stderr or "")[-4000:],
            )
        except OSError as exc:
            return _failure(
                "runtime_failed",
                str(exc),
                returncode=proc.returncode,
                stderr=proc.stderr[-4000:],
            )
        if run.returncode != 0:
            return {
                "status": "runtime_failed",
                "reason": "compiled C++ completion returned a non-zero status",
                "failed_closed": True,
                "returncode": proc.returncode,
                "runtime_returncode": run.returncode,
                "stderr": proc.stderr[-4000:],
                "runtime_stdout": run.stdout[-4000:],
                "runtime_stderr": run.stderr[-4000:],
            }
        return {
            "status": PASS_STATUS,
            "returncode": proc.returncode,
            "runtime_returncode": run.returncode,
            "stderr": proc.stderr[-4000:],
            "runtime_stdout": run.stdout[-4000:],
            "runtime_stderr": run.stderr[-4000:],
        }


def shell_syntax_oracle(
    prompt: DomainEvalPrompt,
    completion: str,
    *,
    shell_executable: str | None = None,
    syntax_timeout_s: float = 10.0,
    tool_overrides: ToolOverrides | None = None,
) -> dict[str, Any]:
    oracle_error = prompt.oracle_contract_error()
    if oracle_error is not None:
        return _failure("missing_shell_oracle", oracle_error)
    domain = _single_domain(prompt, _SHELL_ORACLE_SPECS)
    if domain is None:
        return _failure(
            "missing_shell_oracle",
            "shell_syntax oracle has no single declared shell domain",
        )
    shell_name, parser = _SHELL_ORACLE_SPECS[domain]
    try:
        parsed = parser(completion)
        parsed.validate()
    except (IndexError, TypeError, ValueError) as exc:
        return _failure(
            "shell_parse_failed",
            f"{shell_name} structural parser failed: {exc}",
            shell_kind=shell_name,
        )
    receipt = _parsed_receipt(parsed)
    receipt["shell_kind"] = shell_name
    if parsed.metadata.get("unsupported_syntax") or set(parsed.confidence_ids) == {
        int(ParseConfidence.RAW)
    }:
        return _failure(
            "shell_parse_failed",
            str(parsed.metadata.get("unsupported_syntax", "parser marked syntax RAW")),
            **receipt,
        )
    contract_error = _parsed_oracle_error(
        parsed,
        prompt.oracle_spec,
        allowed_domains=frozenset({domain}),
        context=f"prompt {prompt.id!r} shell oracle",
    )
    if contract_error is not None:
        return _failure(
            "shell_structure_failed",
            contract_error,
            **receipt,
        )
    executable = (
        shell_executable
        if shell_executable is not None
        else _resolve_tool(shell_name, (shell_name,), tool_overrides)
    )
    if executable is None:
        return _failure(
            "shell_oracle_unavailable",
            f"no local {shell_name} executable found",
            **receipt,
        )
    with tempfile.TemporaryDirectory(prefix="cppmega-shell-eval-") as tmp:
        source = Path(tmp) / f"completion.{shell_name}"
        source.write_text(completion, encoding="utf-8")
        try:
            proc = subprocess.run(
                [executable, "-n", str(source)],
                capture_output=True,
                text=True,
                timeout=syntax_timeout_s,
            )
        except subprocess.TimeoutExpired as exc:
            return _failure(
                "shell_syntax_timeout",
                f"{shell_name} syntax check exceeded the timeout",
                timeout_s=syntax_timeout_s,
                stderr=str(exc.stderr or "")[-4000:],
                **receipt,
            )
        except OSError as exc:
            return _failure("shell_oracle_unavailable", str(exc), **receipt)
    if proc.returncode != 0:
        return _failure(
            "shell_syntax_failed",
            f"{shell_name} rejected the completion syntax",
            returncode=proc.returncode,
            stderr=proc.stderr[-4000:],
            stdout=proc.stdout[-4000:],
            **receipt,
        )
    return {
        "status": "shell_syntax_passed",
        "shell_kind": shell_name,
        "executable": executable,
        "stderr": proc.stderr[-4000:],
        "stdout": proc.stdout[-4000:],
        **receipt,
    }


_BUILD_ROLE_REQUIREMENTS: dict[DomainKind, frozenset[DomainRoleKind]] = {
    DomainKind.CMAKE: frozenset({DomainRoleKind.COMMAND}),
    DomainKind.MAKE: frozenset({DomainRoleKind.TARGET, DomainRoleKind.COMMAND}),
    DomainKind.NINJA: frozenset({DomainRoleKind.RULE, DomainRoleKind.OUTPUT}),
    DomainKind.BAZEL: frozenset({DomainRoleKind.RULE, DomainRoleKind.TARGET}),
    DomainKind.CONFIGURE: frozenset(
        {DomainRoleKind.COMMAND, DomainRoleKind.KEYWORD, DomainRoleKind.ENVIRONMENT}
    ),
}


def build_structure_oracle(
    prompt: DomainEvalPrompt,
    completion: str,
) -> dict[str, Any]:
    oracle_error = prompt.oracle_contract_error()
    if oracle_error is not None:
        return _failure("missing_build_oracle", oracle_error)
    domain = _single_domain(prompt, _BUILD_ORACLE_SPECS)
    if domain is None:
        return _failure(
            "missing_build_oracle",
            "build_structure oracle has no single declared build/config domain",
        )
    parser = _BUILD_ORACLE_SPECS[domain]
    try:
        parsed = parser(completion)
        parsed.validate()
    except (IndexError, TypeError, ValueError) as exc:
        return _failure(
            "build_structure_failed",
            f"{domain.name.lower()} structural parser failed: {exc}",
            build_kind=domain.name.lower(),
        )
    receipt = _parsed_receipt(parsed)
    receipt["build_kind"] = domain.name.lower()
    required_roles = _BUILD_ROLE_REQUIREMENTS[domain]
    role_ids = {int(value) for value in parsed.role_ids}
    if parsed.metadata.get("unsupported_syntax") or set(parsed.confidence_ids) == {
        int(ParseConfidence.RAW)
    }:
        return _failure(
            "build_structure_failed",
            str(parsed.metadata.get("unsupported_syntax", "parser marked structure RAW")),
            **receipt,
        )
    contract_error = _parsed_oracle_error(
        parsed,
        prompt.oracle_spec,
        allowed_domains=frozenset({domain}),
        context=f"prompt {prompt.id!r} build oracle",
    )
    if contract_error is not None:
        return _failure(
            "build_structure_failed",
            contract_error,
            **receipt,
        )
    if not role_ids.intersection(int(role) for role in required_roles):
        return _failure(
            "build_structure_failed",
            f"{domain.name.lower()} completion has no recognized structural roles",
            **receipt,
        )
    return {
        "status": "build_structure_passed",
        **receipt,
    }


